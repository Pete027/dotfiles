import secrets


def get_passphrase_count():
    """Запитує кількість слів у користувача."""
    while True:
        try:
            count = int(
                input(
                    "Введіть кількість слів у фразі (рекомендовано 4-6 слів): "
                )
            )
            if count < 3:
                print("⚠️ Менше 3 слів — занадто слабкий пароль. Спробуйте ще раз.")
                continue
            return count
        except ValueError:
            print("❌ Будь ласка, введіть число.")


def generate_passphrase(words_count):
    """Генерує парольну фразу з випадкових українських слів."""
    # Базовий список із 40 різноманітних іменників та дієслів для демонстрації.
    # У реальних системах використовують словники на 2000-4000 слів.
    word_list = [
        "сонце", "літак", "кава", "книга", "робот", "гора", "океан", "ключ",
        "двері", "хмара", "дерево", "вітер", "пісок", "трава", "міст", "весна",
        "літо", "осінь", "зима", "кіт", "собака", "птах", "зоря", "місяць",
        "вогонь", "вода", "земля", "папір", "ручка", "екран", "звук", "світло",
        "карта", "колесо", "яблуко", "замок", "камінь", "ліс", "річка", "шлях"
    ]

    # Вибираємо випадкові слова криптографічно стійким методом secrets.choice
    chosen_words = [secrets.choice(word_list) for _ in range(words_count)]

    # Об'єднуємо слова через дефіс
    return "-".join(chosen_words)


if __name__ == "__main__":
    print("--- Генератор легких для запам'ятовування паролів (Passphrase) ---")
    words_needed = get_passphrase_count()
    passphrase = generate_passphrase(words_needed)

    print("\n✅ Ваша нова безпечна парольна фраза:")
    print(passphrase)
    print(
        "💡 Порада: уявіть сюжет із цих слів у голові, щоб назавжди їх запам'ятати."
    )
